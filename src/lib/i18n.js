const KEY = 'poker-locale'
export const SUPPORTED = ['pt', 'en', 'es']

// 'auto' segue o idioma do aparelho; os demais fixam a escolha.
export const LOCALE_OPTIONS = [
  { id: 'auto', flag: '🌐' },
  { id: 'pt', flag: '🇧🇷', label: 'Português' },
  { id: 'en', flag: '🇺🇸', label: 'English' },
  { id: 'es', flag: '🇪🇸', label: 'Español' },
]

export function detectLocale() {
  try {
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language]
    for (const lang of langs) {
      const code = String(lang).toLowerCase().slice(0, 2)
      if (SUPPORTED.includes(code)) return code
    }
  } catch {
    /* sem navigator (testes/SSR) */
  }
  return 'pt'
}

// Guarda também em memória: no Safari em modo privado o localStorage lança ao
// gravar, e sem isso a escolha de idioma não valeria nem para a sessão atual.
let memoryPref = null

export function readLocalePref() {
  try {
    const stored = localStorage.getItem(KEY)
    if (stored === 'auto' || SUPPORTED.includes(stored)) return stored
  } catch {
    /* segue para a memória */
  }
  return memoryPref || 'auto'
}

export function resolveLocale(pref) {
  return pref === 'auto' ? detectLocale() : pref
}

export function getLocale() {
  return resolveLocale(readLocalePref())
}

const listeners = new Set()

export function setLocalePref(pref) {
  memoryPref = pref
  try {
    localStorage.setItem(KEY, pref)
  } catch {
    /* modo privado ou fora do navegador: a escolha vale só para esta sessão */
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = getLocale()
  }
  listeners.forEach((fn) => fn(pref))
}

export function onLocaleChange(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

