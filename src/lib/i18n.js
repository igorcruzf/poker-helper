function lookup(locale, path) {
  return path.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), DICT[locale])
}

// t('table.level', { level: 2 }) — cai no português se faltar a chave, e devolve
// a própria chave se nem lá existir (fica óbvio na tela em vez de sumir).
export function translate(locale, key, params) {
  let value = lookup(locale, key)
  if (typeof value !== 'string') value = lookup('pt', key)
  if (typeof value !== 'string') return key
  if (!params) return value
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined ? match : String(params[name])
  )
}

export function t(key, params) {
  return translate(getLocale(), key, params)
}
